      program main
c--------------------------------------------------------------------------c
c     solve diakonov petrov gap equation, calculate coordinate space       c
c     correlation function.                                                c
c--------------------------------------------------------------------------c
c     version       :    2.2                                               c
c     creation date :  10-07-94                                            c
c     last modified :  01-04-96                                            c
c--------------------------------------------------------------------------c
c     everything in units of fm, input/output converted                    c
c--------------------------------------------------------------------------c
c     uses either cern or imsl subroutines.                                c
c--------------------------------------------------------------------------c
      implicit real*8 (a-h,o-z)
      real*8 ssa(100),sva(100),xxa(100)
      real*8 pis(100),pips(100),pisig(100),pieta(100)
      common /par/ rho,dens,xm0,nc
      common /cut/ pmax
      common /res/ e
      external f,func,func2
      pi = 3.1415926d0
      rho= 0.33
      nc = 3

      open(unit=16,file='mass.dat',status='unknown')
      open(unit=17,file='cor.dat',status='unknown')

c--------------------------------------------------------------------------c
c     parameters                                                           c
c--------------------------------------------------------------------------c

      write(6,*) 'density (fm^-4)'
      read(5,*) dens
      write(6,*) 'current mass (MeV)'
      read(5,*) xm0
      write(6,*) 'cutoff (rho^-1)'
      read(5,*) pmax
      xm0 = xm0/197.33

c--------------------------------------------------------------------------c
c     solve gap equation                                                   c
c--------------------------------------------------------------------------c

      call solve(e)

c--------------------------------------------------------------------------c
c     output                                                               c
c--------------------------------------------------------------------------c

      xmp0 = 2.0*pi**2*e*dens/nc*rho**2
      xqq  = qq(e)
      xfpi = fpi(e)
      xmpi = sqrt(2.d0*xm0*xqq)/xfpi
 
      write(6,*) 'e^-1 =',197.33/e
      write(6,*) 'M(0) =',xmp0*197.33
      write(6,*) 'M_Q  =',(xm0+xmp0)*197.33
      write(6,*) '<qq> =',xqq**(1./3.) * 197.33
      write(6,*) 'fpi  =',xfpi*197.33
      write(6,*) 'mpi  =',xmpi*197.33
      write(6,*) 'Geff =',xqq/xmp0/4.0/0.197**2

      dp = 20.0/197.33
      do 10 i=1,100
         p = dp*i
         xm= e*dens/(2.0*nc)*p**2*phi(p)**2
         write(16,222) p*197.33,xm*197.33
 10   continue

c--------------------------------------------------------------------------c
c     coordinate space propagator                                          c
c--------------------------------------------------------------------------c

      write(17,*) '   quark propagator'
      write(17,*) '     x            ss           sv'

      dx = 0.1
      nx = 20
      do 20 i=1,nx
         x  = i*dx
         s0 = 1.d0/(2.d0*pi**2*x**3)
         xxa(i) = x
         ssa(i) = ss(x,e)
         sva(i) = sv(x,e)
         write(17,333) x,ssa(i)/s0,sva(i)/s0
 20   continue

c--------------------------------------------------------------------------c
c     vector correlators                                                   c
c--------------------------------------------------------------------------c

      write(17,*)
      write(17,*) '   vector correlators'
      write(17,*) '     x            piv          pia'

      do 30 i=1,nx
         x = xxa(i)
         s0 = 1.d0/(2.d0*pi**2*x**3)
         write(17,333) x,vec(ssa(i),sva(i))/s0**2,0.d0
 30   continue

c--------------------------------------------------------------------------c
c     baryon correlators                                                   c
c--------------------------------------------------------------------------c

      write(17,*)
      write(17,*) '   baryon correlators'
      write(17,*) '     x            nuc          del'

      do 40 i=1,nx
         x = xxa(i)
         s0 = 1.d0/(2.d0*pi**2*x**3)
         write(17,333) x,xnuc(ssa(i),sva(i))/s0**3,
     1                   del(ssa(i),sva(i))/s0**3
 40   continue

c--------------------------------------------------------------------------c
c     scalar correlators                                                   c
c--------------------------------------------------------------------------c

      write(17,*)
      write(17,*) '   scalar correlators'
      write(17,*) '     x            scal         ps'

      do 50 i=1,nx
         x  = xxa(i)
         s0 = 1.d0/(2.d0*pi**2*x**3)
         call piconn(x,pis(i),pips(i),pisig(i),pieta(i))
         sc = pis(i)  + 4.d0*nc*scalunc(ssa(i),sva(i))
         ps = pips(i) + 4.d0*nc*psunc(ssa(i),sva(i))
         pi0= 4.d0*nc*s0**2
         write(17,555) x,sc/pi0,ps/pi0,pis(i)/pi0,pips(i)/pi0
         write(6,555)  x,sc/pi0,ps/pi0,pis(i)/pi0,pips(i)/pi0
 50   continue

c--------------------------------------------------------------------------c
c     flavor singlet correlators                                           c
c--------------------------------------------------------------------------c

      write(17,*)
      write(17,*) '   flavor singlet correlators'
      write(17,*) '     x            sig          eta'

      do 60 i=1,nx
         x  = xxa(i)
         s0 = 1.d0/(2.d0*pi**2*x**3)
         sig= pisig(i) + 4.d0*nc*scalunc(ssa(i),sva(i))
         eta= pieta(i) + 4.d0*nc*psunc(ssa(i),sva(i))
         pi0= 4.d0*nc*s0**2
         write(17,555) x,sig/pi0,eta/pi0,pisig(i)/pi0,pieta(i)/pi0
         write(6,555)  x,sig/pi0,eta/pi0,pisig(i)/pi0,pieta(i)/pi0
 60   continue

c--------------------------------------------------------------------------c
c     that's it                                                            c
c--------------------------------------------------------------------------c

 222  format(2(1x,f12.5))
 333  format(3(1x,f12.5))
 555  format(5(1x,f12.5))

      end

c------------------------------------------------------------------------+-----
