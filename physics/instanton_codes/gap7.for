      function scalunc(ss,sv)
c--------------------------------------------------------------------------c
c     unconnected part of scalar current correlator                        c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)

      scalunc = sv**2-ss**2

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function psunc(ss,sv)
c--------------------------------------------------------------------------c
c     unconnected part of scalar current correlator                        c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)

      psunc = sv**2+ss**2

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function vec(ss,sv)
c--------------------------------------------------------------------------c
c     vector current correlator                                            c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)

      vec = sv**2+2.d0*ss**2

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function del(ss,sv)
c--------------------------------------------------------------------------c
c     delta correlator                                                     c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)

      del = sv**3+3.d0*sv*ss**2

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function xnuc(ss,sv)
c--------------------------------------------------------------------------c
c     nucleon correlator                                                   c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)

      xnuc = sv**3+0.5d0*sv*ss**2

      return
      end

