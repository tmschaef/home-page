      subroutine piconn(x,pisx,pipsx,pisigx,pietax) 
c--------------------------------------------------------------------------c
c     f trafo of connected part of scalar correlators, f-trafo of scalar   c 
c     functions reduces to bessel j1 trafo.                                c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)
      integer  nc,np,ip,init
      real*8 pis(1000),pips(1000),pisig(1000),pieta(1000)
      save pis,pips,pisig,pieta,init
      common /par/ rho,dens,xm0,nc
      common /ev/  e
      common /cut/ pmax

      np   = 100
      
      pi    = 3.1415926d0
      p1max = pmax/rho
      dp    = p1max/np

c--------------------------------------------------------------------------c
c     on first call, store momentum space correlators                      c
c--------------------------------------------------------------------------c

      if(init .eq. 0) then
         do 5 ip=1,np
            p1 = ip*dp
            call piscal(p1,pis(ip),pips(ip),pisig(ip),pieta(ip))
            write(6,*) p1,pis(ip),pips(ip),pisig(ip),pieta(ip)
            write(16,*) p1,pis(ip),pips(ip),pisig(ip),pieta(ip)
            init = 1
  5      continue
      endif

      pissum  = 0.d0
      pipssum = 0.d0
      pisigsum= 0.d0
      pietasum= 0.d0

c--------------------------------------------------------------------------c
c     simpson integration                                                  c
c--------------------------------------------------------------------------c

      do 10 ip=1,np,2

         p1 = ip*dp
         xj1 = dbesj1(p1*x)
         pissum  = pissum   + 4.d0*p1**2*pis(ip)*xj1
         pipssum = pipssum  + 4.d0*p1**2*pips(ip)*xj1
         pisigsum= pisigsum + 4.d0*p1**2*pisig(ip)*xj1
         pietasum= pietasum + 4.d0*p1**2*pieta(ip)*xj1

         p2 = (ip+1)*dp
         xj1 = dbesj1(p2*x)
         pissum  = pissum   + 2.d0*p2**2*pis(ip+1)*xj1
         pipssum = pipssum  + 2.d0*p2**2*pips(ip+1)*xj1
         pisigsum= pisigsum + 2.d0*p2**2*pisig(ip+1)*xj1
         pietasum= pietasum + 2.d0*p2**2*pieta(ip+1)*xj1

 10   continue 
 
c--------------------------------------------------------------------------c
c     normalize                                                            c
c--------------------------------------------------------------------------c

      pisx  =  pissum*dp/6.d0 / (4.d0*pi**2*x)
      pipsx =  pipssum*dp/6.d0/ (4.d0*pi**2*x)
      pisigx=  pisigsum*dp/6.d0/ (4.d0*pi**2*x)
      pietax=  pietasum*dp/6.d0/ (4.d0*pi**2*x)

      end
     
