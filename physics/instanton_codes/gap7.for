      function phi(p)
c--------------------------------------------------------------------------c
c     fourier transform of zero mode profile                               c
c--------------------------------------------------------------------------c
      implicit real*8 (a-h,o-z)
      real*8 k(0:2),i(0:2)
      common /par/ rho,dens,xm0,nc

      pi= 3.1415926d0
      x = p*rho/2.d0
      if (x .gt. 0.d0 .and. x .lt. 80.d0) then
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c        call dbsks(0.0,x,3,k)
c        call dbsins(x,3,i)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
         k(0) = dbesk0(x)
         k(1) = dbesk1(x)
         k(2) = k(0)+2.0/x*k(1)
         i(0) = dbesi0(x)
         i(1) = dbesi1(x)
         i(2) = i(0)-2.0/x*i(1)
      else
         k(0) = 0.d0
         k(1) = 0.d0
         k(2) = 0.d0
         i(0) = 0.d0
         i(1) = 0.d0
         i(2) = 0.d0
      endif
      phi = pi*rho**2/2.d0*( 3.0*i(1)*k(0)-3.0*i(0)*k(1)
     1                                 -i(2)*k(1)+k(2)*i(1) )

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function xmq(p)
c--------------------------------------------------------------------------c
c     momentum dependent constituent quark mass                            c
c--------------------------------------------------------------------------c
      implicit real*8 (a-h,o-z)
      common /par/ rho,dens,xm0,nc
      common /res/ e
      xmq   = e*dens/(2.0*3.0) * p**2 * phi(p)**2
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function xdmq(p)
c--------------------------------------------------------------------------c
c     derivative of momentum dependent constituent quark mass              c
c--------------------------------------------------------------------------c
      implicit real*8 (a-h,o-z)
      common /par/ rho,dens,xm0,nc
      common /res/ e
      eps  = 1.d-5
      xm1  = xmq(p+eps)
      xm2  = xmq(p)
      xdmq = (xm1-xm1)/eps
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      subroutine solve(e)
c--------------------------------------------------------------------------c
c     solve gap equation                                                   c
c--------------------------------------------------------------------------c
      implicit real*8(a-z)
      integer itmax,nroot,mode,nc
      external f
      common /par/ rho,dens,xm0,nc
c--------------------------------------------------------------------------c
      nroot = 1
      itmax = 100
      eps   = 1.0e-6
      errabs= 1.0e-6
      errrel= 1.0e-6
      eta   = 1.0e-3
      error = 1.0e-3
      xguess= 2.0
      x1    = 0.0
      x2    = 4.0
      mode  = 1
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c     call dzreal(f,errabs,errrel,eps,eta,nroot,itmax,xguess,
c    1           e,info)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
      e = dzerox(x1,x2,error,itmax,f,mode)
      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function f(e)
c--------------------------------------------------------------------------c
c     gap equation f(e)==0                                                 c
c--------------------------------------------------------------------------c
      implicit real*8(a-z)
      integer irule, nc
      external func
      common /par/ rho,dens,xm0,nc
      common /ev / ee
      common /cut/ pmax

      pi = 3.1415926d0
      ee = e

c---------------------------------------------------------------------------c
c     calculate integral for lhs                                            c
c---------------------------------------------------------------------------c

      a = 0.0d0
      b = pmax/rho
      errabs = 0.0d0
      errrel = 1.d-6
      irule  = 2
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c     call dqdag(func,a,b,errabs,errrel,irule,result,errest)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
      result = dgauss(func,a,b,errrel)     

      lhs = 1.0/(16.0*pi**2)*result

c--------------------------------------------------------------------------c
c     gap equation                                                         c
c--------------------------------------------------------------------------c

      f = lhs - dens/(4.0*nc)*(1.0-xm0*e)

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function func(p2)
c--------------------------------------------------------------------------c
c     integrand for LHS of gap equation                                    c
c--------------------------------------------------------------------------c

      implicit real*8 (a-z)
      integer  nc
      common /par/ rho,dens,m0,nc
      common /ev/  e

c--------------------------------------------------------------------------c
c     dp gap equation                                                      c
c--------------------------------------------------------------------------c

      xm   = e*dens/(2.0*3.0) * p2 * phi(sqrt(p2))**2
      func = p2 * xm**2/(xm**2+p2)

c--------------------------------------------------------------------------c
c     nowak et al result for m0 dependence                                 c
c--------------------------------------------------------------------------c

c     xm   = e*dens/(2.0*3.0) * p2 * phi(sqrt(p2))**2
c     func = p2 * xm*(xm+m0)/((xm+m0)**2+p2)

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function qq(e)
c--------------------------------------------------------------------------c
c     calculate quark condensate                                           c
c--------------------------------------------------------------------------c

      implicit real*8(a-z)
      integer irule, nc
      external func2
      common /par/ rho,dens,xm0,nc
      common /ev / ee
      common /cut/ pmax

      pi = 3.1415926d0
      ee = e

c---------------------------------------------------------------------------c
c     do the integral                                                       c
c---------------------------------------------------------------------------c

      a = 0.0d0
      b = pmax/rho
      errabs = 0.0d0
      errrel = 1.d-6
      irule  = 2
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c     call dqdag(func2,a,b,errabs,errrel,irule,result,errest)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
      result = dgauss(func2,a,b,errrel)     

      qq = 4.0*nc/(16.0*pi**2)*result

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function func2(p2)
c--------------------------------------------------------------------------c
c     integrand for quark condensate                                       c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)
      integer  nc
      common /par/ rho,dens,m0,nc
      common /ev/  e

      xm   = e*dens/(2.0*3.0) * p2 * phi(sqrt(p2))**2
      func2= p2 * xm/(xm**2+p2)

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function fpi(e)
c--------------------------------------------------------------------------c
c     calculate pion decay constant                                        c
c--------------------------------------------------------------------------c

      implicit real*8(a-z)
      integer irule, nc
      external funcf
      common /par/ rho,dens,xm0,nc
      common /ev / ee
      common /cut/ pmax

      pi = 3.1415926d0
      ee = e

c---------------------------------------------------------------------------c
c     do the integral                                                       c
c---------------------------------------------------------------------------c

      a = 0.0d0
      b = pmax/rho
      errabs = 0.0d0
      errrel = 1.d-6
      irule  = 2
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c     call dqdag(funcf,a,b,errabs,errrel,irule,result,errest)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
      result = dgauss(funcf,a,b,errrel)     

      fpi2 = nc/(4.0*pi**2) * result
      fpi  = sqrt(fpi2)

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function funcf(p2)
c--------------------------------------------------------------------------c
c     integrand for pion decay constant                                    c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)
      integer  nc
      common /par/ rho,dens,m0,nc
      common /ev/  e

      p = sqrt(p2)
      xm  = xmq(p)
      dxm = xdmq(p)
      xm2 = xm**2     
      funcf= p2/(p2+xm2)**2 * (xm2-0.5d0*p*xm*dxm+0.25d0*p2*dxm**2)

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function sv(x,e)
c--------------------------------------------------------------------------c
c     vector part of coordinate space quark propagator                     c
c--------------------------------------------------------------------------c

      implicit real*8 (a-z)
      real*8 k(0:2)
      integer irule,nc
      common /par/ rho,dens,xm0,nc
      common /cut/ pmax
      common /ev/  ee
      common /dis/ xx
      external func3
      pi = 3.1415926d0
      xx = x
      ee = e

c--------------------------------------------------------------------------c
c     subtract free part, do fourier transform of the rest                 c
c--------------------------------------------------------------------------c

      arg = xm0*x
      if (arg .gt. 0.d0 .and. arg .lt. 80.d0) then
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c        call dbsks(0.0,arg,3,k)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
         k(0) = dbesk0(arg)
         k(1) = dbesk1(arg)
         k(2) = k(0)+2.0/arg*k(1)
      else
         k(0) = 0.d0
         k(1) = 0.d0
         k(2) = 0.d0
      endif
      sv0 = xm0**2/(4.0d0*pi**2*x)*k(2)

      a = 0.0d0
      b = pmax/rho
      errabs = 0.0d0
      errrel = 1.d-6
      irule  = 2
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c     call dqdag(func3,a,b,errabs,errrel,irule,result,errest)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
      result = dgauss(func3,a,b,errrel)     

      sv = sv0 + result/(4.0d0*pi**2*x)

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function func3(p)
c--------------------------------------------------------------------------c
c     integrand for vector part of propagator                              c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)
      real*8 j(0:2)
      integer  nc
      common /par/ rho,dens,xm0,nc
      common /ev/  e
      common /dis/ x

      arg = p*x
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c     call dbsjns(arg,3,j)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
      j(0) = dbesj0(arg)
      j(1) = dbesj1(arg)
      j(2) =-j(0)+2.0/arg*j(1)
      p2   = p**2
      xm   = e*dens/(2.0*3.0) * p2 * phi(sqrt(p2))**2
      xfun = 1.0/(p2+(xm+xm0)**2)-1.0/(p2+xm0**2)
      func3= xfun*p**3*j(2)

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function ss(x,e)
c--------------------------------------------------------------------------c
c     scalar part of coordinate space quark propagator                     c
c--------------------------------------------------------------------------c

      implicit real*8 (a-z)
      integer irule,nc
      common /par/ rho,dens,xm0,nc
      common /cut/ pmax
      common /dis/ xx
      common /ev/  ee
      external func4
      pi = 3.1415926d0
      xx = x
      ee = e

c--------------------------------------------------------------------------c
c     subtract free part, do fourier transform of the rest                 c
c--------------------------------------------------------------------------c

      arg = xm0*x
      if (arg .gt. 0.d0 .and. arg .lt. 80.d0) then
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c        xk1 = dbsk1(arg)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
         xk1 = dbesk1(arg)
      else
         xk1= 0.d0
      endif
      ss0 = xm0/(4.0d0*pi**2*x)*xk1

      a = 0.0d0
      b = pmax/rho
      errabs = 0.0d0    
      errrel = 1.d-6
      irule  = 2
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c     call dqdag(func4,a,b,errabs,errrel,irule,result,errest)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
      result = dgauss(func4,a,b,errrel)
      ss = result/(4.0d0*pi**2*x)

      return
      end

c------------------------------------------------------------------------+-----
c------------------------------------------------------------------------+-----

      function func4(p)
c--------------------------------------------------------------------------c
c     integrand for scalar part of propagator                              c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)
      integer  nc
      common /par/ rho,dens,xm0,nc
      common /ev/  e
      common /dis/ x

      arg = p*x
c--------------------------------------------------------------------------c
c     imsl                                                                 c
c--------------------------------------------------------------------------c
c     xj1 = dbsj1(arg)
c--------------------------------------------------------------------------c
c     cern                                                                 c
c--------------------------------------------------------------------------c
      xj1 = dbesj1(arg)
      p2  = p**2
      xm   = e*dens/(2.0*3.0) * p2 * phi(sqrt(p2))**2
      xfun = (xm+xm0)/(p2+(xm+xm0)**2) 
      func4= xfun*p2*xj1

      return
      end

