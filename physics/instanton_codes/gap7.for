      subroutine piscal(p,pis,pips,pisig,pieta) 
c--------------------------------------------------------------------------c
c     connected part of scalar correlators                                 c
c--------------------------------------------------------------------------c
      implicit real*8 (a-z)
      integer  nc,np,ncos,ip,icos
      common /par/ rho,dens,xm0,nc
      common /ev/  e
      common /cut/ pmax

      np   = 100
      ncos = 50
      
      pi    = 3.1415926d0
      p1max = pmax/rho
      dp1   = p1max/np
      dcos  = 2.d0/ncos

      r1sum = 0.d0
      r5sum = 0.d0
      g1sum = 0.d0
      g5sum = 0.d0

c--------------------------------------------------------------------------c
c     two dimensional integration                                          c
c--------------------------------------------------------------------------c

      do 10 ip=1,np
      
         p1    = ip*dp1
         p12   = p1**2
         xm1   = e*dens/(2.0*nc)*p12*phi(p1)**2

         do 20 icos=1,ncos-1

c--------------------------------------------------------------------------c
c     costh is the angle between p1 and p                                  c
c--------------------------------------------------------------------------c

         costh = icos*dcos-1.d0
         sinth = sqrt(1.d0-costh**2)
         p22   = p1**2+p**2-2.d0*p*p1*costh   
         p2    = sqrt(p22)
         p1p2  =-p1*p*costh+p12

         xm2   = e*dens/(2.0*nc)*p22*phi(p2)**2

         den   = (xm1**2+p12)*(xm2**2+p22)
         ts    = xm1*xm2-p1p2
         tps   = xm1*xm2+p1p2
         vol   = p1**3 * sinth

         r1sum = r1sum + xm1*xm2*ts/den*vol
         r5sum = r5sum + xm1*xm2*tps/den*vol
         g1sum = g1sum + sqrt(xm1*xm2)*ts/den*vol
         g5sum = g5sum + sqrt(xm1*xm2)*tps/den*vol

 20      continue
 10   continue

c--------------------------------------------------------------------------c
c     normalize                                                            c
c--------------------------------------------------------------------------c

      fac = dp1*dcos/(4.d0*pi**3)
      r1sum = r1sum*fac 
      r5sum = r5sum*fac 
      g1sum = g1sum*fac 
      g5sum = g5sum*fac 
      
      r1 = 1.d0 - 4.d0*nc/dens*r1sum
      r5 = 1.d0 - 4.d0*nc/dens*r5sum
      rs =-1.d0 - 4.d0*nc/dens*r1sum
      re =-1.d0 - 4.d0*nc/dens*r5sum
      g1 = 4.d0*g1sum
      g5 = 4.d0*g5sum

c--------------------------------------------------------------------------c
c     correlators                                                          c
c--------------------------------------------------------------------------c

       pis  =-nc**2/dens*g1**2/r1
       pips = nc**2/dens*g5**2/r5
       pisig=-nc**2/dens*g1**2/rs
       pieta= nc**2/dens*g5**2/re

       end

c------------------------------------------------------------------------+-----
